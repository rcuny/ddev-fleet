<?php

declare(strict_types=1);

namespace App\Tests\Integration\Fleet\Instances;

use App\Domain\Host\HostSettingsRepository;
use App\Domain\Instance\Instance;
use App\Domain\Port\NamedPort;
use App\Domain\Project\Project;
use App\Fleet\Auth\AdminGroup;
use App\Fleet\FleetPaths;
use App\Fleet\Instances\InstanceHostnames;
use App\Fleet\Instances\InstanceSiteWriter;
use App\Fleet\Shell\CommandResult;
use App\Fleet\Shell\RecordingCommandRunner;
use App\Fleet\System\CaddyfileRenderer;
use App\Fleet\System\CaddyReloader;
use App\Tests\Support\FleetDatabase;
use App\Tests\Support\SystemTemplates;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;
use Symfony\Component\Lock\LockFactory;
use Symfony\Component\Lock\Store\FlockStore;

final class InstanceSiteWriterTest extends KernelTestCase
{
    use FleetDatabase;

    /** The Remote-Groups pattern of the project `acme` with the admin group `fleet-admins`. */
    private const string GROUPS = '(?:^|,)(?:fleet\\-admins|fleet\\-project\\-acme)(?:,|$)';

    private FleetPaths $paths;
    private RecordingCommandRunner $runner;
    private InstanceSiteWriter $writer;

    protected function setUp(): void
    {
        $em = $this->setUpFleetDatabase();
        $paths = self::getContainer()->get(FleetPaths::class);
        self::assertInstanceOf(FleetPaths::class, $paths);
        $this->paths = $paths;
        $host = new HostSettingsRepository($em);
        $host->getOrCreate('fleet.example.com');
        $this->runner = new RecordingCommandRunner();
        $this->writer = new InstanceSiteWriter(
            SystemTemplates::twig(),
            $this->paths,
            new CaddyReloader($this->runner, $this->paths),
            new InstanceHostnames($host),
            new LockFactory(new FlockStore($this->paths->locksDir())),
            new AdminGroup('fleet-admins'),
        );
    }

    protected function tearDown(): void
    {
        $this->tearDownFleetDatabase();
        parent::tearDown();
    }

    private function project(string ...$hostnames): Project
    {
        $project = new Project('acme', 'https://git.example.com/acme/blog.git');
        $project->changeHostnames(array_values($hostnames));

        return $project;
    }

    private function instance(Project $project, string $label = 'main'): Instance
    {
        return new Instance($project, $label, 'full', 'develop', 'admin');
    }

    private function site(string $id = 'acme--main'): string
    {
        return (string) file_get_contents($this->paths->instanceSiteFile($id));
    }

    public function testOneBlockWithAliasesAndTheAuthGate(): void
    {
        $project = $this->project('edge', 'shop');
        $this->writer->write($this->instance($project), $project);
        $site = $this->site();

        self::assertStringContainsString("\nacme--main.fleet.example.com, edge-acme--main.fleet.example.com, shop-acme--main.fleet.example.com {\n", $site);
        self::assertSame(1, preg_match_all('/^\S.* \{$/m', $site), 'one site block');
        self::assertStringContainsString('forward_auth '.CaddyfileRenderer::AUTHELIA.' {', $site);
        self::assertStringContainsString('reverse_proxy '.CaddyfileRenderer::DDEV_ROUTER, $site);
        self::assertLessThan(strpos($site, 'reverse_proxy'), strpos($site, 'forward_auth'), 'the gate comes before the proxy');
        self::assertStringContainsString('Strict-Transport-Security', $site);
        self::assertStringContainsString('-Server', $site);
        self::assertSame(0o640, fileperms($this->paths->instanceSiteFile('acme--main')) & 0o777);
        self::assertCount(1, $this->runner->callsMatching(['caddy', 'reload']));
    }

    public function testTwentyThreeAliasesShareOneBlock(): void
    {
        $labels = array_map(static fn (int $i): string => 'h'.$i, range(1, 23));
        $project = $this->project(...$labels);
        $this->writer->write($this->instance($project), $project);
        $site = $this->site();

        self::assertSame(1, preg_match_all('/^\S.* \{$/m', $site), 'one site block');
        foreach ($labels as $label) {
            self::assertStringContainsString($label.'-acme--main.fleet.example.com', $site);
        }
    }

    /**
     * @param list<NamedPort> $ports
     */
    private function portedProject(array $ports, string ...$hostnames): Project
    {
        $project = $this->project(...$hostnames);
        $project->changePorts($ports);

        return $project;
    }

    public function testNoPortsLeavesTheSnippetAsItWas(): void
    {
        $project = $this->project();
        $this->writer->write($this->instance($project), $project);

        $expected = <<<'CADDY'
            # Generated by Fleet for the instance acme--main; edits are overwritten.
            acme--main.fleet.example.com {
                header {
                    Strict-Transport-Security "max-age=31536000"
                    -Server
                }

                # The identity headers never come from the client. Only Remote-Groups is copied back from Authelia, to check the
                # project group below, and it is removed again: the app behind the instance does not read identity headers.
                route {
                    request_header -Remote-User
                    request_header -Remote_User
                    request_header -Remote-Groups
                    request_header -Remote_Groups
                    request_header -Remote-Name
                    request_header -Remote_Name
                    request_header -Remote-Email
                    request_header -Remote_Email

                    forward_auth 127.0.0.1:9091 {
                        uri /api/authz/forward-auth
                        copy_headers Remote-Groups
                    }

                    # Per-project access: the groups come from Authelia (the client's own header was stripped above).
                    @forbidden not header_regexp Remote-Groups `(?:^|,)(?:fleet\-admins|fleet\-project\-acme)(?:,|$)`
                    respond @forbidden "Forbidden" 403
                    request_header -Remote-Groups

                    reverse_proxy 127.0.0.1:8080
                }
            }

            CADDY;
        self::assertSame($expected, $this->site(), 'byte-identical, whole file');
    }

    public function testAHostileNameOrPortNeverReachesTheTemplate(): void
    {
        $project = $this->portedProject([new NamedPort("x\nreverse_proxy evil", 9108, 8108)]);

        try {
            $this->writer->write($this->instance($project), $project);
            self::fail('expected the name to be refused');
        } catch (\InvalidArgumentException $e) {
            self::assertStringContainsString('not a valid port name', $e->getMessage());
        }
        self::assertSame([], glob($this->paths->caddyInstancesDir().'/*') ?: []);
    }

    public function testOnePortAddsAGatedBlockToTheRouter(): void
    {
        $project = $this->portedProject([new NamedPort('typesense', 9108, 8108)]);
        $this->writer->write($this->instance($project), $project);
        $site = $this->site();

        self::assertStringContainsString("\nacme--main.fleet.example.com:9108 {\n", $site);
        self::assertStringContainsString('reverse_proxy 127.0.0.1:8108', $site);
        self::assertSame(2, preg_match_all('/^\S.* \{$/m', $site), 'the plain site plus one port block');
    }

    public function testThePlaywrightReportPortIsServedOnItsOwnPublicPortAndProxiedToTheAddonRouterPort(): void
    {
        $project = $this->portedProject([new NamedPort('playwright', 9325, 8323)]);
        $this->writer->write($this->instance($project), $project);
        $site = $this->site();

        self::assertStringContainsString("\nacme--main.fleet.example.com:9325 {\n", $site);
        self::assertStringContainsString('reverse_proxy 127.0.0.1:8323', $site);
        self::assertStringContainsString('forward_auth', substr($site, (int) strpos($site, ':9325 {')));
    }

    public function testTwoPortsWithAnAliasAreOrderedAndEveryBlockIsGatedAndStripped(): void
    {
        $project = $this->portedProject([new NamedPort('mail', 9200, 18025), new NamedPort('typesense', 9108, 8108)], 'edge');
        $this->writer->write($this->instance($project), $project);
        $site = $this->site();

        self::assertStringContainsString("\nacme--main.fleet.example.com:9108, edge-acme--main.fleet.example.com:9108 {\n", $site);
        self::assertStringContainsString("\nacme--main.fleet.example.com:9200, edge-acme--main.fleet.example.com:9200 {\n", $site);
        self::assertLessThan(strpos($site, ':9200'), strpos($site, ':9108'), 'ordered by public port');

        $blocks = preg_split('/^(?=\S.* \{$)/m', $site) ?: [];
        array_shift($blocks);
        self::assertCount(3, $blocks);
        foreach ($blocks as $block) {
            self::assertLessThan(strpos($block, 'reverse_proxy'), strpos($block, 'forward_auth'), 'the gate comes before the proxy');
            self::assertLessThan(strpos($block, 'forward_auth'), strpos($block, 'request_header'), 'the strip runs before the gate');
            foreach (CaddyfileRenderer::strippedHeaders() as $header) {
                self::assertStringContainsString('request_header -'.$header."\n", $block);
            }
            self::assertSame(1, substr_count($block, 'copy_headers Remote-Groups'), 'only the groups are read back from Authelia');
            self::assertSame(1, substr_count($block, 'copy_headers'));
            self::assertStringContainsString('@forbidden not header_regexp Remote-Groups `'.self::GROUPS.'`', $block);
            self::assertStringContainsString('respond @forbidden "Forbidden" 403', $block);
            self::assertLessThan(strpos($block, 'respond @forbidden'), strpos($block, 'forward_auth'), 'the group check follows the gate');
            self::assertLessThan(strpos($block, 'reverse_proxy'), strpos($block, 'respond @forbidden'), 'and comes before the proxy');
        }
    }

    public function testAPortCaddyOrTheRouterAlreadyUsesIsRefused(): void
    {
        foreach ([[new NamedPort('web', 8080, 18080)], [new NamedPort('ssl', 443, 18443)], [new NamedPort('loop', 9108, 8080)]] as $ports) {
            $project = $this->portedProject($ports);
            try {
                $this->writer->write($this->instance($project), $project);
                self::fail('expected the port to be refused');
            } catch (\InvalidArgumentException $e) {
                self::assertStringContainsString('reserved for the host', $e->getMessage());
            }
        }
        self::assertSame([], glob($this->paths->caddyInstancesDir().'/*') ?: []);
        self::assertSame([], $this->runner->calls());
    }

    public function testTheSiteAdmitsTheAdminGroupAndThisProjectsGroupOnly(): void
    {
        $project = $this->project();
        $this->writer->write($this->instance($project), $project);
        $site = $this->site();

        self::assertStringContainsString('@forbidden not header_regexp Remote-Groups `(?:^|,)(?:fleet\-admins|fleet\-project\-acme)(?:,|$)`', $site);
        self::assertStringContainsString("request_header -Remote-Groups\n", $site);
        self::assertStringNotContainsString('fleet-project-other', $site);
    }

    public function testTheGroupPatternIsAnchoredToWholeListEntries(): void
    {
        $project = $this->project();
        $this->writer->write($this->instance($project), $project);
        $pattern = '/'.str_replace('/', '\\/', self::GROUPS).'/';
        self::assertStringContainsString('`'.self::GROUPS.'`', $this->site());

        foreach (['fleet-project-acme', 'a,fleet-project-acme', 'fleet-project-acme,b', 'fleet-admins', 'x,fleet-admins,y'] as $allowed) {
            self::assertSame(1, preg_match($pattern, $allowed), $allowed);
        }
        foreach (['', 'fleet-project-acme-x', 'x-fleet-project-acme', 'fleet-project-acm', 'fleet-project-other', 'fleet-admins2', 'myfleet-admins'] as $denied) {
            self::assertSame(0, preg_match($pattern, $denied), $denied);
        }
    }

    public function testOnlyTheGroupsAreReadBackAndAllRemoteHeadersStripped(): void
    {
        $project = $this->project();
        $this->writer->write($this->instance($project), $project);
        $site = $this->site();

        self::assertSame(1, substr_count($site, 'copy_headers Remote-Groups'));
        self::assertSame(1, substr_count($site, 'copy_headers'));
        foreach (CaddyfileRenderer::strippedHeaders() as $header) {
            self::assertStringContainsString('request_header -'.$header."\n", $site);
        }
        self::assertLessThan(strpos($site, 'forward_auth'), strpos($site, 'request_header'), 'the strip runs before the gate');
    }

    public function testReloadFailureRestoresThePreviousFile(): void
    {
        $project = $this->project();
        $this->writer->write($this->instance($project), $project);
        $before = $this->site();

        $this->runner->expect(['caddy', 'validate'], new CommandResult(1, '', 'Error: bad config'));
        $withAlias = $this->project('edge');
        try {
            $this->writer->write($this->instance($withAlias), $withAlias);
            self::fail('expected the failure to be rethrown');
        } catch (\RuntimeException $e) {
            self::assertStringContainsString('bad config', $e->getMessage());
        }

        self::assertSame($before, $this->site());
    }

    public function testReloadFailureWithNoPreviousLeavesNothing(): void
    {
        $this->runner->expect(['caddy', 'validate'], new CommandResult(1, '', 'Error: bad config'));
        $project = $this->project();

        try {
            $this->writer->write($this->instance($project), $project);
            self::fail('expected the failure to be rethrown');
        } catch (\RuntimeException) {
            $this->addToAssertionCount(1);
        }

        self::assertFileDoesNotExist($this->paths->instanceSiteFile('acme--main'));
        self::assertSame([], glob($this->paths->caddyInstancesDir().'/*') ?: []);
    }

    public function testRemoveDeletesAndReloads(): void
    {
        $project = $this->project();
        $this->writer->write($this->instance($project), $project);
        $this->runner->reset();

        $this->writer->remove('acme--main');

        self::assertFileDoesNotExist($this->paths->instanceSiteFile('acme--main'));
        self::assertCount(1, $this->runner->callsMatching(['caddy', 'reload']));

        $this->runner->reset();
        $this->writer->remove('acme--main');
        self::assertSame([], $this->runner->calls(), 'a missing site is fine and needs no reload');
    }

    public function testBadIdAndNewlineInHostnameAreRefused(): void
    {
        try {
            $this->writer->remove('../etc');
            self::fail('expected the id to be refused');
        } catch (\InvalidArgumentException) {
            $this->addToAssertionCount(1);
        }

        $hostile = $this->project("edge\nrespond 200");
        try {
            $this->writer->write($this->instance($hostile), $hostile);
            self::fail('expected the host name to be refused');
        } catch (\InvalidArgumentException) {
            $this->addToAssertionCount(1);
        }
        self::assertSame([], glob($this->paths->caddyInstancesDir().'/*') ?: []);
        self::assertSame([], $this->runner->calls());
    }

    public function testValidateOnlyValidates(): void
    {
        $this->writer->validate();

        self::assertCount(1, $this->runner->callsMatching(['caddy', 'validate']));
        self::assertSame([], $this->runner->callsMatching(['caddy', 'reload']));
    }
}
