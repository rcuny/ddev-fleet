<?php

declare(strict_types=1);

namespace App\Tests\Unit\Fleet\System;

use App\Domain\Host\HostSettings;
use App\Fleet\FleetPaths;
use App\Fleet\System\AutheliaConfigRenderer;
use App\Fleet\System\AutheliaNotifier;
use App\Tests\Support\SystemTemplates;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Yaml\Yaml;

final class AutheliaConfigRendererTest extends TestCase
{
    private static function renderer(string $home = '/srv/fleet', ?AutheliaNotifier $notifier = null): AutheliaConfigRenderer
    {
        return new AutheliaConfigRenderer(SystemTemplates::twig(), new FleetPaths($home, '/etc/caddy/fleet'), $notifier);
    }

    public function testRegulationIsRenderedExplicitly(): void
    {
        $config = Yaml::parse(self::renderer()->render(new HostSettings('fleet.example.com')));

        self::assertSame(
            ['max_retries' => AutheliaConfigRenderer::MAX_RETRIES, 'find_time' => '2m', 'ban_time' => '5m'],
            $config['regulation'],
        );
        self::assertSame(5, AutheliaConfigRenderer::BAN_MINUTES);
    }

    public function testBanNoticeNamesTheUserAndTheRenderedBanTime(): void
    {
        $notice = AutheliaConfigRenderer::banNotice('alice');

        self::assertStringContainsString('"alice"', $notice);
        self::assertStringContainsString('up to 5 minutes', $notice);
    }

    public function testGolden(): void
    {
        $expected = <<<'YAML'
            # Generated by Fleet and installed by `apply authelia`; edits are overwritten. Secrets are supplied through
            # AUTHELIA_*_FILE variables, never written here.
            server:
              address: 'tcp://127.0.0.1:9091/'
            log:
              level: info
            authentication_backend:
              password_reset:
                disable: true
              file:
                path: '/srv/fleet/authelia/users.yml'
                watch: true
              # Re-read the user's groups on every request, so a membership change applies at once (the file is small and local).
              refresh_interval: always
            session:
              cookies:
                - domain: 'fleet.example.com'
                  authelia_url: 'https://auth.fleet.example.com'
            storage:
              local:
                path: '/var/lib/authelia/db.sqlite3'
            regulation:
              max_retries: 3
              find_time: '2m'
              ban_time: '5m'
            notifier:
              filesystem:
                filename: '/var/lib/authelia/notification.txt'
            access_control:
              default_policy: deny
              rules:
                - domain: 'auth.fleet.example.com'
                  policy: bypass
                - domain: 'fleet.example.com'
                  policy: one_factor
                # Instance hosts: any signed-in user. Which project a user may open is checked by the instance's Caddy site from
                # the Remote-Groups header, so access changes never touch this file (and never restart Authelia).
                - domain: '*.fleet.example.com'
                  policy: one_factor

            YAML;

        self::assertSame($expected, self::renderer()->render(new HostSettings('fleet.example.com')));
    }

    public function testTheOutputIsValidYamlWithTheExpectedStructure(): void
    {
        $parsed = Yaml::parse(self::renderer()->render(new HostSettings('fleet.example.com')));

        self::assertIsArray($parsed);
        self::assertSame('deny', $parsed['access_control']['default_policy']);
        self::assertTrue($parsed['authentication_backend']['password_reset']['disable']);
        self::assertSame('https://auth.fleet.example.com', $parsed['session']['cookies'][0]['authelia_url']);
        self::assertArrayNotHasKey('secret', $parsed['session'], 'secrets come from AUTHELIA_*_FILE, never from this file');
    }

    public function testPerProjectAccessIsNotPartOfTheConfiguration(): void
    {
        $out = self::renderer()->render(new HostSettings('fleet.example.com'));
        $rules = Yaml::parse($out)['access_control']['rules'];

        // One static rule for every instance host and no subject: nothing here changes with a project or a user.
        self::assertSame(['domain' => '*.fleet.example.com', 'policy' => 'one_factor'], $rules[2]);
        self::assertCount(3, $rules);
        self::assertStringNotContainsString('domain_regex', $out);
        self::assertStringNotContainsString('subject', $out);
    }

    public function testUsersPathComesFromFleetPaths(): void
    {
        $paths = new FleetPaths('/data/fleet-x', '/etc/caddy/fleet');

        $out = new AutheliaConfigRenderer(SystemTemplates::twig(), $paths)->render(new HostSettings('fleet.example.com'));

        self::assertStringContainsString("path: '".$paths->usersFile()."'", $out);
        self::assertStringContainsString("path: '/data/fleet-x/authelia/users.yml'", $out);
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function injectedDomains(): iterable
    {
        foreach (["a.example.com'\npolicy: bypass", 'a.example.com\'', "a.example.com\n", 'a.example.com: x', 'a.example.com #x', '*.example.com', '{{x}}.example.com', 'a.example.com"'] as $value) {
            yield addcslashes($value, "\n") => [$value];
        }
    }

    #[DataProvider('injectedDomains')]
    public function testRefusesADomainThatCouldChangeTheYamlStructure(string $domain): void
    {
        $this->expectException(\InvalidArgumentException::class);

        self::renderer()->render(new HostSettings($domain));
    }

    public function testRefusesAHomeThatCouldChangeTheYamlStructure(): void
    {
        $this->expectException(\InvalidArgumentException::class);

        self::renderer("/srv/fl'eet")->render(new HostSettings('fleet.example.com'));
    }

    public function testSelfServiceResetIsDisabledWithoutANotifier(): void
    {
        foreach ([null, new AutheliaNotifier(), new AutheliaNotifier('', '', ''), new AutheliaNotifier(null, 'fleet@example.com')] as $notifier) {
            $out = self::renderer('/srv/fleet', $notifier)->render(new HostSettings('fleet.example.com'));
            $parsed = Yaml::parse($out);

            self::assertTrue($parsed['authentication_backend']['password_reset']['disable']);
            self::assertSame(['filesystem' => ['filename' => '/var/lib/authelia/notification.txt']], $parsed['notifier']);
        }
    }

    public function testSelfServiceResetIsEnabledWithAnSmtpNotifier(): void
    {
        $notifier = new AutheliaNotifier('submission://mail.example.com:587', 'fleet@example.com', 'fleet-mailer');

        $out = self::renderer('/srv/fleet', $notifier)->render(new HostSettings('fleet.example.com'));
        $parsed = Yaml::parse($out);

        self::assertFalse($parsed['authentication_backend']['password_reset']['disable']);
        self::assertSame(['smtp' => ['address' => 'submission://mail.example.com:587', 'sender' => 'fleet@example.com', 'username' => 'fleet-mailer']], $parsed['notifier']);
        self::assertStringNotContainsString('password:', $out, 'the SMTP password is supplied through AUTHELIA_NOTIFIER_SMTP_PASSWORD_FILE, never rendered');
        self::assertTrue(new AutheliaNotifier('smtp://localhost', 'fleet@example.com')->isConfigured());
    }

    public function testTheSmtpUsernameIsOptional(): void
    {
        $out = self::renderer('/srv/fleet', new AutheliaNotifier('smtp://localhost:25', 'fleet@example.com'))->render(new HostSettings('fleet.example.com'));

        self::assertSame(['smtp' => ['address' => 'smtp://localhost:25', 'sender' => 'fleet@example.com']], Yaml::parse($out)['notifier']);
    }

    /**
     * @return iterable<string, array{AutheliaNotifier}>
     */
    public static function badNotifiers(): iterable
    {
        yield 'sender missing' => [new AutheliaNotifier('smtp://mail.example.com', null)];
        yield 'address without scheme' => [new AutheliaNotifier('mail.example.com', 'fleet@example.com')];
        yield 'address with a path' => [new AutheliaNotifier('smtp://mail.example.com/x', 'fleet@example.com')];
        yield 'address with a quote' => [new AutheliaNotifier("smtp://mail.example.com'", 'fleet@example.com')];
        yield 'sender not an email' => [new AutheliaNotifier('smtp://mail.example.com', "fleet@example.com'\n")];
        yield 'username with a quote' => [new AutheliaNotifier('smtp://mail.example.com', 'fleet@example.com', "me'")];
    }

    #[DataProvider('badNotifiers')]
    public function testRefusesBadNotifierSettings(AutheliaNotifier $notifier): void
    {
        $this->expectException(\InvalidArgumentException::class);

        self::renderer('/srv/fleet', $notifier)->render(new HostSettings('fleet.example.com'));
    }
}
