# shellcheck shell=bash
# shellcheck disable=SC2034  # the change flags and results are read by the other steps (one shell sources them all)
# Step 70: the application's environment, generated once.
#   /etc/ddev-fleet/fleet.env     root:fleet 0640  read by php-fpm (unit drop-in), the workers and the `fleet` wrapper
#   /etc/ddev-fleet/mercure.env   root:root  0600  the Mercure hub's keys (read by systemd), derived from the same secret
# Only MISSING keys are added: a re-run (= an upgrade) never regenerates a secret, and a value an operator changed
# stays. The files are plain KEY=VALUE lines without quoting, so systemd and `set -a; . file` read them alike.
#
# The tests run this step as an unprivileged user against a scratch directory: they source common.sh and this file,
# set FLEET_ETC_DIR (and DOMAIN), stub chown and call step_main.

# env_ensure <file> <mode> <owner:group> KEY=VALUE...   (VALUE @secret = 64 random hex characters, generated once)
env_ensure() {
  local file=$1 mode=$2 owner=$3 spec key value existing='' content added=''
  shift 3
  if is_dry; then
    for spec in "$@"; do
      key=${spec%%=*}
      value=${spec#*=}
      printf '+ env %s: %s=%s (only when missing)\n' "$file" "$key" "$([ "$value" = @secret ] && echo '<64 hex, generated once>' || echo "$value")"
    done
    write_file "$file" "$mode" "$owner" </dev/null
    return 0
  fi
  if [ -f "$file" ]; then
    existing=$(cat "$file")
  fi
  content=$existing
  if [ -z "$content" ]; then
    content="# Generated by the ddev-fleet installer. Read by systemd (EnvironmentFile) and by the fleet command. A re-run only adds
# keys that are missing; edit a value here and the installer keeps it."
  fi
  for spec in "$@"; do
    key=${spec%%=*}
    value=${spec#*=}
    if grep -Eq "^${key}=" <<<"$existing"; then
      continue
    fi
    if [ "$value" = @secret ]; then
      value=$(openssl rand -hex 32)
    fi
    content+=$'\n'"$key=$value"
    added+=" $key"
  done
  printf '%s\n' "$content" | write_file "$file" "$mode" "$owner"
  if [ -n "$added" ]; then
    log_info "$file: added$added"
  fi
}

# The value of KEY in an env file (last assignment wins, like a shell sourcing it).
env_value() {
  sed -n "s/^$2=//p" "$1" | tail -n 1
}

step_main() {
  local env_file="$FLEET_ETC_DIR/fleet.env" mercure_env="$FLEET_ETC_DIR/mercure.env" secret uri

  ensure_dir "$FLEET_ETC_DIR" 0750 root:fleet
  env_ensure "$env_file" 0640 root:fleet \
    APP_ENV=prod \
    APP_DEBUG=0 \
    APP_SECRET=@secret \
    MERCURE_JWT_SECRET=@secret \
    FLEET_PROXY_SECRET=@secret \
    "FLEET_HOME=$FLEET_SRV_DIR" \
    FLEET_RUNNER=process \
    FLEET_TRUSTED_PROXIES= \
    FLEET_ADMIN_GROUP=fleet-admins \
    "FLEET_CADDY_DIR=$CADDY_FLEET_DIR" \
    "DEFAULT_URI=https://$DOMAIN"
  [ "$FILE_CHANGED" = 0 ] || ENV_CHANGED=1

  if is_dry; then
    printf '+ env %s: MERCURE_PUBLISHER_JWT_KEY and MERCURE_SUBSCRIBER_JWT_KEY = MERCURE_JWT_SECRET of fleet.env\n' "$mercure_env"
    write_file "$mercure_env" 0600 root:root </dev/null
    return 0
  fi

  uri=$(env_value "$env_file" DEFAULT_URI)
  if [ "$uri" != "https://$DOMAIN" ]; then
    log_warn "DEFAULT_URI in $env_file is $uri, not https://$DOMAIN; kept (edit it by hand after a domain change)"
  fi

  # Derived, so rewritten from the current secret on every run (it can never drift from fleet.env).
  secret=$(env_value "$env_file" MERCURE_JWT_SECRET)
  [[ $secret =~ ^[A-Za-z0-9._~+/=-]{32,}$ ]] || die 1 "MERCURE_JWT_SECRET in $env_file is missing or unusable"
  printf '%s\n' \
    '# Generated by the ddev-fleet installer from MERCURE_JWT_SECRET in fleet.env.' \
    "MERCURE_PUBLISHER_JWT_KEY=$secret" \
    "MERCURE_SUBSCRIBER_JWT_KEY=$secret" |
    write_file "$mercure_env" 0600 root:root
  [ "$FILE_CHANGED" = 0 ] || MERCURE_CHANGED=1
}
