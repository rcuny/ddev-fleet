"""In-network mirror of the fleet's public named ports (FLE-29).

The fleet's named ports (`fleet.ports` catalogue + the built-in Typesense
`9108`) exist only on the host's Caddy (`core/caddyports.py`:
`*.<domain>:<public>` -> `127.0.0.1:<router>`). Inside an instance's
containers the instance FQDN resolves to `ddev-router` on the Docker network,
which does not listen on those public ports, so an in-container browser
(Playwright) cannot reach `https://<fqdn>:<public>` - the URL the site hands to
the client.

This module makes `ddev-router` (Traefik) listen on the same public ports
INSIDE the Docker network only. It writes two generic files into the fleet
user's DDEV global Traefik directory (`~/.ddev/traefik/`):

* `static_config.fleet-port-mirror.yaml` - one entrypoint per port. DDEV merges
  every `static_config.*.yaml` into its generated static config on `ddev start`
  and does NOT publish these ports on the host, so there is no clash with Caddy.
* `custom-global-config/fleet-port-mirror.yaml` - one TCP router per entrypoint
  (`HostSNI(*)`, TLS terminated with the certificates DDEV already loads) that
  forwards the plaintext to the router's OWN http entrypoint
  (`127.0.0.1:<router>`), whose existing Host rules pick the instance.

Apply model: `sync()` only writes files and never touches the router. DDEV
copies/merges them on the next `ddev start`; the static config is only read when
the router starts, so `converge()` (called right after a successful instance
`ddev start`) restarts `ddev-router` only when its live entrypoints differ from
what the registry wants, and self-repairs (removes the files, re-merges,
restarts again) if the router does not come back with the mirror.

Safety nets: a failed apply leaves a marker file (`FAILED_MARKER`) holding the
wanted ports; while it matches, neither `sync()` nor `converge()` act, so a
broken mirror cannot cause a router restart on every deploy
(`fleet refresh-ports` clears it, the explicit retry). `converge()` and the
`sync()` calls of deploy/destroy/refresh-ports are serialised with a
`flock` on `<fleet home>/locks/_routermirror.lock` (bounded wait, never fatal).
"""

import contextlib
import errno
import fcntl
import http.client
import json
import logging
import re
import time
import urllib.error
import urllib.request
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

from ruamel.yaml import YAML

from fleet.core import caddyauth, ddev
from fleet.core.errors import CaddyAuthError, RouterMirrorError
from fleet.core.registry import PortProfile, Registry
from fleet.core.runner import run_streamed

logger = logging.getLogger(__name__)

DEFAULT_TRAEFIK_DIR = Path.home() / ".ddev" / "traefik"
STATIC_FILENAME = "static_config.fleet-port-mirror.yaml"
DYNAMIC_RELPATH = Path("custom-global-config") / "fleet-port-mirror.yaml"
ENTRYPOINT_PREFIX = "fleet-mirror-"
TRAEFIK_API = "http://127.0.0.1:10999"
FAILED_MARKER = ".fleet-port-mirror-failed"
LOCK_NAME = "_routermirror.lock"

# DDEV router's own entrypoints on the fleet hosts (http/https, http/https on
# the loopback ports, mailpit, Traefik API).
RESERVED_PORTS = frozenset({80, 443, 8080, 8443, 8025, 8026, 10999})

_HEADER = (
    "# Managed by ddev-fleet (FLE-29): do not edit. "
    "Regenerated by deploy / fleet refresh-ports.\n"
)

_API_TIMEOUT = 5.0
_ROUTER_CONTAINER = "ddev-router"
_HEALTH_POLL_SECONDS = 2.0
_RESTART_TIMEOUT = 120.0
_INSPECT_TIMEOUT = 10.0
_LOCK_WAIT = 300.0
_LOCK_POLL_SECONDS = 1.0
_HEALTH_TEMPLATE = "{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}"
_ADDRESS_PORT_RE = re.compile(r":(\d+)(?:/\w+)?$")


def _entrypoint_name(profile: PortProfile) -> str:
    return f"{ENTRYPOINT_PREFIX}{profile.public}"


def _foreign_entrypoints(traefik_dir: Path) -> tuple[dict[int, str], dict[str, str]]:
    """`({port: filename}, {entrypoint name: filename})` for every entrypoint
    declared by a `static_config.*.yaml` in `traefik_dir` that is not ours (the
    port only when its address is `[host]:<port>`). An unparsable file is
    ignored with a warning."""
    ports: dict[int, str] = {}
    names: dict[str, str] = {}
    yaml = YAML(typ="safe")
    for path in sorted(traefik_dir.glob("static_config.*.yaml")):
        if path.name == STATIC_FILENAME:
            continue
        try:
            data = yaml.load(path.read_text(encoding="utf-8"))
            entrypoints = data.get("entryPoints") if isinstance(data, dict) else None
            if not isinstance(entrypoints, dict):
                continue
            for name, entry in entrypoints.items():
                names.setdefault(str(name), path.name)
                address = entry.get("address") if isinstance(entry, dict) else None
                match = _ADDRESS_PORT_RE.search(address) if isinstance(address, str) else None
                if match:
                    ports.setdefault(int(match.group(1)), path.name)
        except Exception as exc:  # noqa: BLE001 - a foreign file must never break us
            logger.warning("router port mirror: ignoring unparsable %s: %s", path, exc)
    return ports, names


def live_mirror_names(live: set[str], traefik_dir: Path | None = None) -> set[str]:
    """The live `fleet-mirror-*` entrypoints that are OURS: entrypoints with
    that prefix declared by a foreign `static_config.*.yaml` (e.g. a leftover
    spike file) are not ours and are ignored, so they cannot cause restarts."""
    traefik_dir = traefik_dir if traefik_dir is not None else DEFAULT_TRAEFIK_DIR
    foreign = set(_foreign_entrypoints(traefik_dir)[1]) if traefik_dir.is_dir() else set()
    return {n for n in live if n.startswith(ENTRYPOINT_PREFIX)} - foreign


def mirror_profiles(
    registry: Registry, *, traefik_dir: Path | None = None
) -> tuple[list[PortProfile], list[str]]:
    """The profiles to mirror, sorted by public port, plus a human-readable
    reason for every profile that was skipped.

    A colliding entrypoint would stop the shared router from starting and take
    every instance down, so a profile whose `public` port is one of the router's
    own (`RESERVED_PORTS`), equals ANY catalogue profile's `router` port (the
    mirror forwards to that port), duplicates an earlier profile's `public`, or
    is already declared as an entrypoint by another `static_config.*.yaml` in
    `traefik_dir` (when given) is skipped - never raised. `[]` when
    `fleet.port_mirror` is false."""
    if not registry.port_mirror_enabled:
        return [], []
    catalogue = registry.all_port_profiles()
    router_ports = {p.router for p in catalogue}
    foreign, foreign_names = (
        _foreign_entrypoints(traefik_dir) if traefik_dir is not None else ({}, {})
    )
    selected: list[PortProfile] = []
    skipped: list[str] = []
    seen_public: dict[int, str] = {}
    for profile in sorted(catalogue, key=lambda p: (p.public, p.name)):
        prefix = f"port {profile.name!r} (public {profile.public}) not mirrored: "
        if profile.public in RESERVED_PORTS:
            skipped.append(prefix + "the port is used by ddev-router itself")
        elif profile.public in router_ports:
            skipped.append(prefix + "the port is also a router (upstream) port of the catalogue")
        elif profile.public in seen_public:
            skipped.append(prefix + f"duplicate of {seen_public[profile.public]!r}")
        elif _entrypoint_name(profile) in foreign_names:
            skipped.append(
                prefix + f"{foreign_names[_entrypoint_name(profile)]} already declares the "
                f"entrypoint {_entrypoint_name(profile)!r} (delete that file to mirror this port)"
            )
        elif profile.public in foreign:
            skipped.append(
                prefix + f"{foreign[profile.public]} already declares an entrypoint on "
                f":{profile.public} (delete that file to mirror this port)"
            )
        else:
            seen_public[profile.public] = profile.name
            selected.append(profile)
    return selected, skipped


def render_static(profiles: list[PortProfile]) -> str:
    """Traefik static-config fragment: one entrypoint per profile."""
    out = [_HEADER, "entryPoints:\n"]
    for p in profiles:
        out.append(f"  {_entrypoint_name(p)}:\n")
        out.append(f'    address: ":{p.public}"\n')
    return "".join(out)


def render_dynamic(profiles: list[PortProfile]) -> str:
    """Traefik dynamic-config fragment: a TLS-terminating TCP router and
    service per profile, forwarding to the router's own http entrypoint."""
    out = [_HEADER, "tcp:\n", "  routers:\n"]
    for p in profiles:
        name = _entrypoint_name(p)
        out.append(f"    {name}:\n")
        out.append(f"      entryPoints: [{name}]\n")
        out.append('      rule: "HostSNI(`*`)"\n')
        out.append(f"      service: {name}\n")
        out.append("      tls: {}\n")
    out.append("  services:\n")
    for p in profiles:
        name = _entrypoint_name(p)
        out.append(f"    {name}:\n")
        out.append("      loadBalancer:\n")
        out.append("        servers:\n")
        out.append(f'          - address: "127.0.0.1:{p.router}"\n')
    return "".join(out)


@dataclass
class MirrorSyncResult:
    changed: bool = False
    mirrored: list[int] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)


def _files(traefik_dir: Path) -> tuple[Path, Path]:
    return traefik_dir / STATIC_FILENAME, traefik_dir / DYNAMIC_RELPATH


def _remove_files(traefik_dir: Path) -> bool:
    removed = False
    for path in _files(traefik_dir):
        try:
            path.unlink()
            removed = True
        except FileNotFoundError:
            pass
    return removed


def _write_if_changed(path: Path, content: str, *, prefix: str) -> bool:
    try:
        if path.read_text(encoding="utf-8") == content:
            return False
    except FileNotFoundError:
        pass
    caddyauth._atomic_write(path, content, prefix=prefix, mode=0o644)
    return True


def lock_path_for(locks_dir: Path) -> Path:
    return locks_dir / LOCK_NAME


@contextlib.contextmanager
def _router_lock(lock_path: Path | None, *, wait: float, sleep, monotonic):
    """Yield True once the exclusive flock on `lock_path` is held (False after
    `wait` seconds of polling without getting it). `lock_path=None` means
    "no locking" (always True)."""
    if lock_path is None:
        yield True
        return
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    fh = open(lock_path, "a+")
    acquired = False
    try:
        deadline = monotonic() + wait
        while True:
            try:
                fcntl.flock(fh.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
                acquired = True
                break
            except OSError as exc:
                if exc.errno not in (errno.EAGAIN, errno.EWOULDBLOCK):
                    raise
            if monotonic() >= deadline:
                break
            sleep(_LOCK_POLL_SECONDS)
        yield acquired
    finally:
        if acquired:
            fcntl.flock(fh.fileno(), fcntl.LOCK_UN)
        fh.close()


def _ports_text(profiles: list[PortProfile]) -> str:
    return ",".join(str(p) for p in sorted(p.public for p in profiles))


def _marker_path(traefik_dir: Path) -> Path:
    return traefik_dir / FAILED_MARKER


def _read_marker(traefik_dir: Path) -> str | None:
    try:
        return _marker_path(traefik_dir).read_text(encoding="utf-8").strip()
    except OSError:
        return None


def clear_failed_marker(traefik_dir: Path | None = None) -> bool:
    """Delete the failed-apply marker; True if there was one."""
    traefik_dir = traefik_dir if traefik_dir is not None else DEFAULT_TRAEFIK_DIR
    try:
        _marker_path(traefik_dir).unlink()
        return True
    except FileNotFoundError:
        return False


def _marker_blocks(traefik_dir: Path, profiles: list[PortProfile]) -> bool:
    """True while the marker matches the current wanted set. A marker for a
    different set (or when nothing is wanted any more) is deleted."""
    recorded = _read_marker(traefik_dir)
    if recorded is None:
        return False
    if profiles and recorded == _ports_text(profiles):
        return True
    try:
        clear_failed_marker(traefik_dir)
    except OSError as exc:
        logger.warning("router port mirror: cannot remove %s: %s", _marker_path(traefik_dir), exc)
        return True
    return False


def _marker_skip_reason(traefik_dir: Path) -> str:
    return (
        f"mirror disabled: a previous apply failed ({_marker_path(traefik_dir)} present); "
        "fix the cause, then run `fleet refresh-ports` to retry"
    )


def sync(
    registry: Registry,
    *,
    traefik_dir: Path | None = None,
    lock_path: Path | None = None,
    lock_wait: float = _LOCK_WAIT,
    sleep=time.sleep,
    monotonic=time.monotonic,
) -> MirrorSyncResult:
    """Write (or, when nothing is to be mirrored, delete) the two Traefik files
    under `traefik_dir` (default: `DEFAULT_TRAEFIK_DIR`, resolved at call time).
    Files are written atomically and only when their content differs. Never
    touches the router (see `converge()`). While the failed-apply marker matches
    the wanted ports nothing is written. `lock_path` (if given) serialises this
    with `converge()`; if it cannot be taken in `lock_wait` seconds nothing is
    written."""
    traefik_dir = traefik_dir if traefik_dir is not None else DEFAULT_TRAEFIK_DIR
    with _router_lock(lock_path, wait=lock_wait, sleep=sleep, monotonic=monotonic) as acquired:
        if not acquired:
            return MirrorSyncResult(
                skipped=["another deploy holds the router-mirror lock; files not updated"]
            )
        return _sync_locked(registry, traefik_dir)


def _sync_locked(registry: Registry, traefik_dir: Path) -> MirrorSyncResult:
    if not traefik_dir.is_dir():
        _profiles, skipped = mirror_profiles(registry)
        logger.warning(
            "router port mirror: %s does not exist (DDEV not initialised for this user); "
            "nothing written",
            traefik_dir,
        )
        return MirrorSyncResult(
            changed=False,
            mirrored=[],
            skipped=[
                *skipped,
                f"{traefik_dir} does not exist (DDEV not initialised for this user)",
            ],
        )
    profiles, skipped = mirror_profiles(registry, traefik_dir=traefik_dir)
    if _marker_blocks(traefik_dir, profiles):
        return MirrorSyncResult(
            changed=False, mirrored=[], skipped=[*skipped, _marker_skip_reason(traefik_dir)]
        )

    static_path, dynamic_path = _files(traefik_dir)
    if not profiles:
        return MirrorSyncResult(changed=_remove_files(traefik_dir), mirrored=[], skipped=skipped)

    try:
        changed = _write_if_changed(
            static_path, render_static(profiles), prefix=".fleet-port-mirror-static-"
        )
        changed |= _write_if_changed(
            dynamic_path, render_dynamic(profiles), prefix=".fleet-port-mirror-dynamic-"
        )
    except CaddyAuthError as exc:
        raise OSError(exc.message) from exc
    return MirrorSyncResult(changed=changed, mirrored=[p.public for p in profiles], skipped=skipped)


def _http_fetch(url: str):
    with urllib.request.urlopen(url, timeout=_API_TIMEOUT) as resp:  # noqa: S310 - loopback URL
        return json.load(resp)


def live_entrypoints(*, fetch: Callable[[str], object] | None = None) -> set[str] | None:
    """Names of the entrypoints the running ddev-router has, from Traefik's API
    on the loopback; `None` when it is unreachable or answers nonsense.
    `fetch` (url -> decoded JSON) is injectable for tests."""
    fetch = fetch if fetch is not None else _http_fetch
    try:
        data = fetch(f"{TRAEFIK_API}/api/entrypoints")
    except (OSError, ValueError, urllib.error.URLError, http.client.HTTPException):
        return None
    if not isinstance(data, list) or not data:
        return None
    names: set[str] = set()
    for entry in data:
        name = entry.get("name") if isinstance(entry, dict) else None
        if not isinstance(name, str):
            return None
        names.add(name)
    return names


def _router_healthy(runner, *, wait_timeout: float, sleep) -> bool:
    attempts = int(wait_timeout // _HEALTH_POLL_SECONDS) + 1
    for attempt in range(attempts):
        try:
            result = runner(
                ["docker", "inspect", "-f", _HEALTH_TEMPLATE, _ROUTER_CONTAINER],
                echo=False,
                timeout=_INSPECT_TIMEOUT,
            )
            states = {line.strip() for line in result.lines}
            if result.returncode == 0 and states & {"healthy", "running"}:
                return True
        except Exception as exc:  # noqa: BLE001 - treated as "not healthy (yet)"
            logger.warning("router port mirror: docker inspect failed: %s", exc)
        if attempt < attempts - 1:
            sleep(_HEALTH_POLL_SECONDS)
    return False


def _restart_router(runner) -> bool:
    try:
        result = runner(
            ["docker", "restart", _ROUTER_CONTAINER], echo=False, timeout=_RESTART_TIMEOUT
        )
    except Exception as exc:  # noqa: BLE001 - FleetError, OSError, subprocess.TimeoutExpired...
        logger.warning("router port mirror: docker restart failed: %s", exc)
        return False
    return result.returncode == 0


def _files_current(traefik_dir: Path, profiles: list[PortProfile]) -> bool:
    """Both fleet files exist with exactly what `sync()` would write now (or,
    when nothing is wanted, neither exists)."""
    static_path, dynamic_path = _files(traefik_dir)
    if not profiles:
        return not static_path.exists() and not dynamic_path.exists()
    try:
        return static_path.read_text(encoding="utf-8") == render_static(
            profiles
        ) and dynamic_path.read_text(encoding="utf-8") == render_dynamic(profiles)
    except OSError:
        return False


def converge(
    registry: Registry,
    *,
    instance_dir: Path,
    traefik_dir: Path | None = None,
    runner=run_streamed,
    fetch: Callable[[str], object] | None = None,
    wait_timeout: float = 60.0,
    sleep=time.sleep,
    monotonic=time.monotonic,
    lock_path: Path | None = None,
    lock_wait: float = _LOCK_WAIT,
) -> str:
    """Make the live ddev-router match the registry's wanted mirror.

    Call ONLY right after a successful `ddev start` of an instance (DDEV has
    then just merged/copied the files). Returns a message for the deploy log
    (empty when nothing had to be done). Runs under the router-mirror lock
    (`lock_path`; skipped with a message if it cannot be taken in `lock_wait`
    seconds). Never restarts the router while the failed-apply marker matches
    the wanted ports, or when the fleet files are missing/stale. Otherwise
    restarts `ddev-router` only when its live `fleet-mirror-*` entrypoints
    differ from the wanted set; if it does not come back healthy with the
    mirror, removes both fleet files, writes the failed-apply marker, re-runs
    `ddev start` in `instance_dir` (DDEV re-merges its static config without
    ours), restarts the router again and raises `RouterMirrorError`."""
    traefik_dir = traefik_dir if traefik_dir is not None else DEFAULT_TRAEFIK_DIR
    profiles, _skipped = mirror_profiles(registry, traefik_dir=traefik_dir)
    with _router_lock(lock_path, wait=lock_wait, sleep=sleep, monotonic=monotonic) as acquired:
        if not acquired:
            return "another deploy holds the router-mirror lock; skipped"
        return _converge_locked(
            profiles,
            instance_dir=instance_dir,
            traefik_dir=traefik_dir,
            runner=runner,
            fetch=fetch,
            wait_timeout=wait_timeout,
            sleep=sleep,
        )


def _converge_locked(
    profiles: list[PortProfile],
    *,
    instance_dir: Path,
    traefik_dir: Path,
    runner,
    fetch,
    wait_timeout: float,
    sleep,
) -> str:
    wanted = {_entrypoint_name(p) for p in profiles}

    if _marker_blocks(traefik_dir, profiles):
        return (
            "port mirror disabled after a failed apply; router not restarted "
            "(run `fleet refresh-ports` to retry)"
        )
    if not _files_current(traefik_dir, profiles):
        return "port mirror files missing or stale; router not restarted"

    # Read AFTER taking the lock: a concurrent deploy may have just fixed it.
    live = live_entrypoints(fetch=fetch)
    if live is None:
        return "" if not wanted else "router API unreachable; port mirror not verified"
    if live_mirror_names(live, traefik_dir) == wanted:
        return ""

    reason = ""
    if not _restart_router(runner):
        reason = "docker restart ddev-router failed"
    elif not _router_healthy(runner, wait_timeout=wait_timeout, sleep=sleep):
        reason = f"ddev-router was not healthy within {wait_timeout:g}s after the restart"
    else:
        after = None
        for attempt in range(5):
            after = live_entrypoints(fetch=fetch)
            if after is not None and live_mirror_names(after, traefik_dir) == wanted:
                ports = sorted(p.public for p in profiles)
                shown = ", ".join(str(p) for p in ports) if ports else "none"
                return f"restarted ddev-router: port mirror now {shown}"
            if attempt < 4:
                sleep(1.0)
        live_now = sorted(live_mirror_names(after or set(), traefik_dir))
        reason = (
            "ddev-router restarted but its live entrypoints still differ from the wanted "
            f"mirror (wanted {sorted(wanted)}, live {live_now})"
        )

    # Self-repair: never leave the shared router down because of our files, and
    # never retry the same failing apply on every deploy (marker).
    repair_notes: list[str] = []
    steps = (
        ("could not remove the mirror files", lambda: _remove_files(traefik_dir)),
        (
            "could not write the failed-apply marker",
            lambda: _marker_path(traefik_dir).write_text(
                _ports_text(profiles) + "\n", encoding="utf-8"
            ),
        ),
    )
    for label, step in steps:
        try:
            step()
        except Exception as exc:  # noqa: BLE001
            repair_notes.append(f"{label} ({exc})")
    try:
        start = ddev.start(instance_dir, runner=runner)
        if start.returncode != 0:
            repair_notes.append(f"`ddev start` exited {start.returncode}")
    except Exception as exc:  # noqa: BLE001
        repair_notes.append(f"`ddev start` failed ({getattr(exc, 'message', exc)})")
    if not _restart_router(runner):
        repair_notes.append("second `docker restart ddev-router` failed")
    detail = f" Self-repair problems: {'; '.join(repair_notes)}." if repair_notes else ""
    raise RouterMirrorError(
        f"in-network port mirror could not be applied: {reason}. The mirror files "
        f"({STATIC_FILENAME}, {DYNAMIC_RELPATH}) were removed, `ddev start` re-run in "
        f"{instance_dir.name} and ddev-router restarted again, so the router runs "
        f"without the mirror.{detail} The mirror stays off ({FAILED_MARKER} in "
        f"{traefik_dir}) until you run `fleet refresh-ports`. In-container access to "
        "the named ports does not work until this is fixed; check `docker logs "
        "ddev-router`, or set `fleet.port_mirror: false` to disable the mirror."
    )


