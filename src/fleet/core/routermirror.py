"""In-network mirror of the fleet's public named ports (FLE-29).

The fleet's named ports (`fleet.ports` catalogue + the built-in Typesense
`9108`) exist only on the host's Caddy (`core/caddyports.py`:
`*.<domain>:<public>` -> `127.0.0.1:<router>`). Inside an instance's
containers the instance FQDN resolves to `ddev-router` on the Docker network,
which does not listen on those public ports, so an in-container browser
(Playwright) cannot reach `https://<fqdn>:<public>` - the URL the site hands to
the client.

This module makes `ddev-router` (Traefik) listen on the same public ports
INSIDE the Docker network only. It writes two generic files into the fleet
user's DDEV global Traefik directory (`~/.ddev/traefik/`):

* `static_config.fleet-port-mirror.yaml` - one entrypoint per port. DDEV merges
  every `static_config.*.yaml` into its generated static config on `ddev start`
  and does NOT publish these ports on the host, so there is no clash with Caddy.
* `custom-global-config/fleet-port-mirror.yaml` - one TCP router per entrypoint
  (`HostSNI(*)`, TLS terminated with the certificates DDEV already loads) that
  forwards the plaintext to the router's OWN http entrypoint
  (`127.0.0.1:<router>`), whose existing Host rules pick the instance.

Apply model: `sync()` only writes files and never touches the router. DDEV
copies/merges them on the next `ddev start`; the static config is only read when
the router starts, so `converge()` (called right after a successful instance
`ddev start`) restarts `ddev-router` only when its live entrypoints differ from
what the registry wants, and self-repairs (removes the files, re-merges,
restarts again) if the router does not come back with the mirror.

Site mirror on :443 (FLE-32): on the fleet hosts DDEV's `router_https_port` is
`8443` (Caddy owns the host's 443), so inside the Docker network
`https://<fleet host>/` is refused and only `https://<fleet host>:8443/`
works - which puts `:8443` in the Host header and breaks exact-hostname matching
in multi-domain apps. The site mirror is ONE extra entry in the SAME two files:
an entrypoint `fleet-mirror-443` on `:443` and a TLS PASSTHROUGH TCP router that
forwards the raw stream to the router's own https entrypoint (`router_https_port`
from `~/.ddev/global_config.yaml`), which terminates TLS with DDEV's certificates,
routes by Host (no port) and sets `X-Forwarded-Proto: https`. Skipped when
`router_https_port` is already 443 or a foreign static config owns `:443`. The
same `fleet.port_mirror` switch covers it.

Safety nets: a failed apply leaves a marker file (`FAILED_MARKER`) holding the
wanted ports; while it matches, neither `sync()` nor `converge()` act, so a
broken mirror cannot cause a router restart on every deploy
(`fleet refresh-ports` clears it, the explicit retry). `converge()` and the
`sync()` calls of deploy/destroy/refresh-ports are serialised with a
`flock` on `<fleet home>/locks/_routermirror.lock` (bounded wait, never fatal).
"""

